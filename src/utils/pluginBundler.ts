import JSZip from 'jszip';

export interface PluginFile {
  name: string;
  path: string;
  content: string;
  description: string;
}

export interface PluginDefinition {
  id: string;
  name: string;
  codeName: string;
  version: string;
  serviceUrl: string;
  description: string;
  yamlContent: string;
  updateYamlContent: string;
  sourceFiles: {
    bridge: string;
    universal: string;
    session: string;
    main: string;
    wrapper: string;
  };
}

export function generateBundleJs(plugin: PluginDefinition): string {
  const parts = [
    `// ==========================================`,
    `// Hedon Haven Plugin Bundle: ${plugin.name} (${plugin.codeName})`,
    `// Version: ${plugin.version}`,
    `// Target: QuickJS JavaScript Runtime`,
    `// Generated by Hedon Haven Plugin Studio`,
    `// ==========================================\n`,
    `// ==== START: bridge_functions.js ====`,
    plugin.sourceFiles.bridge,
    `// ==== END: bridge_functions.js ====\n`,
    `// ==== START: universal_formats.js ====`,
    plugin.sourceFiles.universal,
    `// ==== END: universal_formats.js ====\n`,
    `// ==== START: session.js ====`,
    plugin.sourceFiles.session,
    `// ==== END: session.js ====\n`,
    `// ==== START: main.js ====`,
    plugin.sourceFiles.main,
    `// ==== END: main.js ====\n`,
    `// ==== START: wrapper.js ====`,
    plugin.sourceFiles.wrapper,
    `// ==== END: wrapper.js ====\n`,
  ];

  return parts.join('\n');
}

export async function createPluginZipBlob(plugin: PluginDefinition): Promise<Blob> {
  const zip = new JSZip();
  const bundleCode = generateBundleJs(plugin);

  // Root requirements for Hedon Haven plugin contract:
  // 1. plugin.yaml at root
  // 2. bundle.js at root
  zip.file('plugin.yaml', plugin.yamlContent);
  zip.file('bundle.js', bundleCode);
  zip.file('update.yaml', plugin.updateYamlContent);

  // Also include source files under src/ for reference / building
  const srcFolder = zip.folder('src');
  if (srcFolder) {
    srcFolder.file('bridge_functions.js', plugin.sourceFiles.bridge);
    srcFolder.file('universal_formats.js', plugin.sourceFiles.universal);
    srcFolder.file('session.js', plugin.sourceFiles.session);
    srcFolder.file('main.js', plugin.sourceFiles.main);
    srcFolder.file('wrapper.js', plugin.sourceFiles.wrapper);
  }

  return await zip.generateAsync({
    type: 'blob',
    compression: 'DEFLATE',
    compressionOptions: { level: 9 },
  });
}

export function downloadBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
